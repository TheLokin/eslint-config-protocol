import { mkdir, writeFile } from "node:fs/promises"
import { dirname } from "node:path"
import { fileURLToPath } from "node:url"
import { builtinRules } from "eslint/use-at-your-own-risk"
import { protocol } from "../src"
import { compileRule, flatConfigsToPlugins, pluginsToRules } from "./plugins"

const __filename = fileURLToPath(import.meta.url)
const __dirname = dirname(__filename)

const configs = await protocol({
  gitignore: true,
  typescript: {
    erasableOnly: true,
    tsconfigPath: "tsconfig.json",
  },
  jsx: {
    a11y: true,
  },
  react: true,
  nextjs: true,
  vue: {
    a11y: true,
  },
  svelte: true,
  solid: true,
  angular: true,
  astro: true,
  node: true,
  imports: true,
  regexp: true,
  jsdoc: true,
  test: true,
  jsonc: true,
  yaml: true,
  toml: true,
  markdown: true,
}).prepend({
  plugins: {
    "": { rules: Object.fromEntries(builtinRules.entries()) },
  },
})

const configNames = configs.map((config) => config.name).filter(Boolean) as string[]
const plugins = await flatConfigsToPlugins(configs)
const rules = await pluginsToRules(plugins)
rules.sort(([a], [b]) => a.localeCompare(b))

const resolved = await Promise.all(rules.map(([name, rule]) => compileRule(name, rule)))
const typeDeclarations = resolved
  .flatMap(({ name, typeDeclarations }, index) => {
    if (typeDeclarations.length > 0) {
      const prefix = index > 0 ? "\n" : ""
      typeDeclarations.unshift(`${prefix}// ${name}`)
    }

    return typeDeclarations
  })
  .join("\n")

const content = [
  [
    `/*`,
    ` * AUTO-GENERATED FILE - DO NOT EDIT`,
    ` *`,
    ` * Generated by the typegen script from the resolved ESLint config. It declares`,
    ` * the available rules, their options and the parser types.`,
    ` *`,
    ` * Manual changes are lost on the next run. Update the generation script`,
    ` * instead.`,
    ` */`,
  ].join("\n"),

  `import type { Linter } from "eslint"`,

  [
    `export interface RuleOptions {`,
    ...resolved.flatMap(({ typeName, name, jsdoc }, index, array) => {
      const isLast = index === array.length - 1
      const { description, tags } = jsdoc.reduce(
        (acc, comment) => {
          const isTag = comment.trimStart().startsWith("@")
          acc[isTag ? "tags" : "description"].push(comment)

          return acc
        },
        { description: [] as string[], tags: [] as string[] },
      )
      const comments =
        description.length && tags.length
          ? [...description, "", ...tags]
          : [...description, ...tags]

      return [
        `  /**\n${comments
          .map((comment) => (comment ? `   * ${comment}` : `   *`))
          .join("\n")
          .replaceAll("*/", "*\\/")}\n   */`,
        `  "${name}"?: Linter.RuleEntry<${typeName}>`,
        ...(isLast ? [] : [""]),
      ].join("\n")
    }),
    `}`,
  ].join("\n"),

  typeDeclarations,

  `export type ConfigNames = ${configNames.map((config) => `"${config}"`).join(" | ")}`,
]

const signature = `${content.join("\n\n")}\n`

const path = `${__dirname}/../src/types/rules.d.ts`
const dir = dirname(path)

await mkdir(dir, { recursive: true })
await writeFile(path, signature, "utf8")
